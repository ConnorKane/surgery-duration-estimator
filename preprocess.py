# STAGE 6 — PERSIST
# =========================================================================== #
print("\n=== STAGE 6: Persist artifacts ===")
log("\n---\n\n## Stage 6 — Persisted artifacts")

# Order columns: id, features, label. Keep label out of the "feature" list.
